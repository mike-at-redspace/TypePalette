// Helper function to create a full config from headline, body, and mono fonts
const createPresetConfig = (
  headlineFont,
  headlineCategory,
  headlineWeight,
  headlineTracking,
  headlineLeading,
  bodyFont,
  bodyCategory,
  bodyWeight,
  bodyTracking,
  bodyLeading,
  monoFont,
  monoCategory = 'Monospace'
) => {
  const headingConfig = {
    family: headlineFont,
    category: headlineCategory,
    weight: headlineWeight,
    tracking: headlineTracking,
    leading: headlineLeading,
    transform: 'none'
  }

  const bodyBaseConfig = {
    family: bodyFont,
    category: bodyCategory,
    weight: bodyWeight,
    tracking: bodyTracking,
    leading: bodyLeading,
    transform: 'none'
  }

  const monoConfig = {
    family: monoFont,
    category: monoCategory,
    weight: '400',
    tracking: '0',
    leading: '1.6',
    transform: 'none'
  }

  return {
    headings: {
      all: headingConfig,
      h1: { ...headingConfig },
      h2: { ...headingConfig },
      h3: { ...headingConfig },
      h4: { ...headingConfig },
      h5: { ...headingConfig },
      h6: { ...headingConfig }
    },
    body: {
      all: bodyBaseConfig,
      paragraph: { ...bodyBaseConfig },
      strong: {
        ...bodyBaseConfig,
        weight: String(Math.min(parseInt(bodyWeight) + 200, 900))
      },
      emphasis: { ...bodyBaseConfig },
      blockquote: { ...bodyBaseConfig },
      code: { ...monoConfig },
      link: { ...bodyBaseConfig }
    },
    ui: {
      all: {
        ...bodyBaseConfig,
        weight: '500',
        tracking: '0.02',
        leading: '1.4',
        transform: 'uppercase'
      },
      button: {
        ...bodyBaseConfig,
        weight: '500',
        tracking: '0.02',
        leading: '1.4',
        transform: 'uppercase'
      },
      label: {
        ...bodyBaseConfig,
        weight: '500',
        tracking: '0.02',
        leading: '1.4',
        transform: 'uppercase'
      },
      input: {
        ...bodyBaseConfig,
        weight: '400',
        tracking: '0',
        leading: '1.4',
        transform: 'none'
      }
    }
  }
}

